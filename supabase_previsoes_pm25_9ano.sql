-- Tabela exclusiva para a atividade de Plano Cartesiano & PM 2,5 (9º Ano)
-- Projeto Supabase: terceiroremota14 (https://bxvuqwnmqooxaoexnjty.supabase.co)
-- Nenhuma tabela existente de outras turmas é alterada.

create table if not exists public.previsoes_pm25_9ano (
  id bigint generated by default as identity primary key,
  turma text default '9º Ano',
  aluno_nome text not null,
  hora_prevista text default '06h',
  pm25_previsto integer not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table public.previsoes_pm25_9ano enable row level security;

drop policy if exists "Permitir insert anonimo 9ano" on public.previsoes_pm25_9ano;
create policy "Permitir insert anonimo 9ano"
  on public.previsoes_pm25_9ano
  for insert to anon
  with check (true);

drop policy if exists "Permitir leitura publica 9ano" on public.previsoes_pm25_9ano;
create policy "Permitir leitura publica 9ano"
  on public.previsoes_pm25_9ano
  for select to anon
  using (true);
